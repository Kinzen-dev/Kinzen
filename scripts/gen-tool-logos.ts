/**
 * Extract the brand marks the tools surfaces use from Simple Icons.
 *
 *   pnpm logos:gen
 *
 * `simple-icons` is a devDependency only: the site ships the few marks below, never the package.
 * Marks keep their official colour and proportions. The only change: black (or near-black) marks
 * render in currentColor so they read in the dark theme. A mark whose colour has too little
 * contrast against the chip surface in one theme sits on a contrasting tile in that theme
 * (`badge`) instead of being recoloured. Simple Icons' disclaimer applies: the marks are their
 * owners' trademarks.
 *
 * Output (committed):
 *   public/tool-logos.svg                     one <symbol> per mark, drawn with <use> (one cached
 *                                             request; the path data stays out of every page's
 *                                             HTML and RSC payload)
 *   src/components/tools/logos.generated.ts   title, colour and badge per mark, plus the sprite URL
 */
